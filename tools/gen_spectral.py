#!/usr/bin/env python3
"""Generates src/SpectralData.h from spectral.js (https://github.com/rvanwijnen/spectral.js, MIT).
Usage: python3 tools/gen_spectral.py path/to/spectral.js"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(sys.argv[1], encoding="utf-8").read()


def array_after(label, text):
    i = text.index(label)
    j = text.index("[", i)
    depth, k = 0, j
    while True:
        if text[k] == "[":
            depth += 1
        elif text[k] == "]":
            depth -= 1
            if depth == 0:
                break
        k += 1
    return text[j:k + 1]


def nums(s):
    return [float(x) for x in re.findall(r"-?\d+\.?\d*(?:e-?\d+)?", s)]


spectra = src[src.index("BASE_SPECTRA = Object.freeze"):src.index("const CIE")]
out = ["// Generated by tools/gen_spectral.py from spectral.js (c) 2025 Ronald van Wijnen, MIT License.",
       "// https://github.com/rvanwijnen/spectral.js", "#pragma once", "", "namespace Spectral::Data", "{",
       "\tinline constexpr int kSize = 38;"]
for name in "WCMYRGB":
    v = nums(array_after(f"{name}: [", spectra))
    assert len(v) == 38, (name, len(v))
    out.append(f"\tinline constexpr double k{name}[kSize] = {{ " + ", ".join(repr(x) for x in v) + " };")
cmf = array_after("CMF: [", src[src.index("const CIE"):])
rows = re.findall(r"\[([^\[\]]+)\]", cmf)
assert len(rows) == 3
out.append("\tinline constexpr double kCMF[3][kSize] = {")
for r in rows:
    v = nums(r)
    assert len(v) == 38
    out.append("\t\t{ " + ", ".join(repr(x) for x in v) + " },")
out.append("\t};")
conv = src[src.index("const CONVERSION"):]
for name in ("XYZ_RGB", "RGB_XYZ", "XYZ_LMS", "LMS_XYZ", "LMS_LAB", "LAB_LMS"):
    v = nums(array_after(f"{name}: [", conv))
    assert len(v) == 9, (name, v)
    out.append(f"\tinline constexpr double k{name}[3][3] = {{ {{ {v[0]!r}, {v[1]!r}, {v[2]!r} }}, {{ {v[3]!r}, {v[4]!r}, {v[5]!r} }}, {{ {v[6]!r}, {v[7]!r}, {v[8]!r} }} }};")
out += ["}", ""]
open(os.path.join(ROOT, "src", "SpectralData.h"), "w").write("\n".join(out))
print("wrote src/SpectralData.h")
